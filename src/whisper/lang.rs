/// Token ids of every language, in the same order as [`LANGUAGES`].
pub fn language_token_ids(tokenizer: &Tokenizer) -> Result<Vec<u32>, String> {
    LANGUAGES
        .iter()
        .map(|(code, _)| {
            tokenizer
                .token_to_id(&format!("<|{code}|>"))
                .ok_or_else(|| format!("tokenizer has no language token <|{code}|>"))
        })
        .collect()
}

/// True when the tokenizer carries the multilingual language tokens (English
/// only models such as `*.en` do not).
pub fn is_multilingual(tokenizer: &Tokenizer) -> bool {
    LANGUAGES
        .iter()
        .all(|(code, _)| tokenizer.token_to_id(&format!("<|{code}|>")).is_some())
}

/// Human readable name for a language code, if it is a known Whisper language.
pub fn language_name(code: &str) -> Option<&'static str> {
    LANGUAGES
        .iter()
        .find(|(c, _)| c.eq_ignore_ascii_case(code))
        .map(|(_, name)| *name)
}
